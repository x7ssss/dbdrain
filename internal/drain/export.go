// -------------------------------------------------------------------------
// BFS traversal — SQL emission path
// -------------------------------------------------------------------------

func (e *Exporter) bfsParents(ctx context.Context, tx pgx.Tx, w io.Writer, startTable string) error {
	queue := []string{startTable}
	enqueued := map[string]bool{startTable: true}

	for len(queue) > 0 {
		table := queue[0]
		queue = queue[1:]

		// Regular FK parents.
		for _, edge := range e.g.OutEdges[table] {
			parent := edge.ToTable
			if parent == table || len(edge.ToColumns) != 1 {
				continue
			}
			fkVals := e.visitedPKs(table)
			if len(fkVals) == 0 {
				continue
			}
			where := fmt.Sprintf("%s IN (%s)", quoteIdent(edge.ToColumns[0]), formatStringList(fkVals))
			if _, err := e.fetchAndEmit(ctx, tx, w, parent, where, 0); err != nil {
				return err
			}
			if !enqueued[parent] {
				enqueued[parent] = true
				queue = append(queue, parent)
			}
		}

		// Virtual FK (polymorphic) parents.
		if err := e.resolveVirtualParents(ctx, tx, w, table, &queue, enqueued); err != nil {
			return err
		}
	}
	return nil
}

func (e *Exporter) bfsChildren(ctx context.Context, tx pgx.Tx, w io.Writer, startTable string, _ int) error {
	type work struct {
		table string
		depth int
	}
	queue := []work{{startTable, 0}}
	enqueued := map[string]bool{startTable: true}

	for len(queue) > 0 {
		item := queue[0]
		queue = queue[1:]

		if e.cfg.MaxDepth > 0 && item.depth >= e.cfg.MaxDepth {
			continue
		}

		for _, edge := range e.g.InEdges[item.table] {
			child := edge.FromTable
			if child == item.table || len(edge.FromColumns) != 1 {
				continue
			}
			fkVals := e.visitedPKs(item.table)
			if len(fkVals) == 0 {
				continue
			}
			where := fmt.Sprintf("%s IN (%s)", quoteIdent(edge.FromColumns[0]), formatStringList(fkVals))
			if _, err := e.fetchAndEmit(ctx, tx, w, child, where, e.cfg.MaxRowsPerTable); err != nil {
				return err
			}
			if !enqueued[child] {
				enqueued[child] = true
				queue = append(queue, work{child, item.depth + 1})
			}
		}
	}
	return nil
}

// resolveVirtualParents resolves polymorphic parents for `table` using captured polyData.
func (e *Exporter) resolveVirtualParents(ctx context.Context, tx pgx.Tx, w io.Writer, table string, queue *[]string, enqueued map[string]bool) error {
	for _, ve := range e.g.VirtualEdges[table] {
		discGroups := e.polyData[table][ve.DiscriminatorCol]
		// Group fk values by discriminator value.
		grouped := map[string][]string{} // discVal -> []fkVal
		for _, pp := range discGroups {
			grouped[pp.discVal] = append(grouped[pp.discVal], pp.fkVal)
		}
		for discVal, fkVals := range grouped {
			tc, ok := ve.Mappings[discVal]
			if !ok {
				continue // unknown discriminator value in this slice
			}
			where := fmt.Sprintf("%s IN (%s)", quoteIdent(tc.Column), formatStringList(fkVals))
			if _, err := e.fetchAndEmit(ctx, tx, w, tc.Table, where, 0); err != nil {
				return fmt.Errorf("virtual FK parent fetch (%s→%s): %w", table, tc.Table, err)
			}
			if !enqueued[tc.Table] {
				enqueued[tc.Table] = true
				*queue = append(*queue, tc.Table)
			}
		}
	}
	return nil
}

