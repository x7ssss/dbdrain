// BFS traversal — target streaming path
// -------------------------------------------------------------------------

func (e *Exporter) collectParents(ctx context.Context, tx pgx.Tx, startTable string, out *[]Row) error {
	queue := []string{startTable}
	enqueued := map[string]bool{startTable: true}

	for len(queue) > 0 {
		table := queue[0]
		queue = queue[1:]

		for _, edge := range e.g.OutEdges[table] {
			parent := edge.ToTable
			if parent == table || len(edge.ToColumns) != 1 {
				continue
			}
			fkVals := e.visitedPKs(table)
			if len(fkVals) == 0 {
				continue
			}
			where := fmt.Sprintf("%s IN (%s)", quoteIdent(edge.ToColumns[0]), formatStringList(fkVals))
			if err := e.collectRows(ctx, tx, parent, where, 0, out); err != nil {
				return err
			}
			if !enqueued[parent] {
				enqueued[parent] = true
				queue = append(queue, parent)
			}
		}

		// Virtual FK polymorphic parents.
		if err := e.collectVirtualParentRows(ctx, tx, table, out, &queue, enqueued); err != nil {
			return err
		}
	}
	return nil
}

func (e *Exporter) collectChildren(ctx context.Context, tx pgx.Tx, startTable string, _ int, out *[]Row) error {
	type work struct {
		table string
		depth int
	}
	queue := []work{{startTable, 0}}
	enqueued := map[string]bool{startTable: true}

	for len(queue) > 0 {
		item := queue[0]
		queue = queue[1:]
		if e.cfg.MaxDepth > 0 && item.depth >= e.cfg.MaxDepth {
			continue
		}
		for _, edge := range e.g.InEdges[item.table] {
			child := edge.FromTable
			if child == item.table || len(edge.FromColumns) != 1 {
				continue
			}
			fkVals := e.visitedPKs(item.table)
			if len(fkVals) == 0 {
				continue
			}
			where := fmt.Sprintf("%s IN (%s)", quoteIdent(edge.FromColumns[0]), formatStringList(fkVals))
			if err := e.collectRows(ctx, tx, child, where, e.cfg.MaxRowsPerTable, out); err != nil {
				return err
			}
			if !enqueued[child] {
				enqueued[child] = true
				queue = append(queue, work{child, item.depth + 1})
			}
		}
	}
	return nil
}

func (e *Exporter) collectVirtualParentRows(ctx context.Context, tx pgx.Tx, table string, out *[]Row, queue *[]string, enqueued map[string]bool) error {
	for _, ve := range e.g.VirtualEdges[table] {
		grouped := map[string][]string{}
		for _, pp := range e.polyData[table][ve.DiscriminatorCol] {
			grouped[pp.discVal] = append(grouped[pp.discVal], pp.fkVal)
		}
		for discVal, fkVals := range grouped {
			tc, ok := ve.Mappings[discVal]
			if !ok {
				continue
			}
			where := fmt.Sprintf("%s IN (%s)", quoteIdent(tc.Column), formatStringList(fkVals))
			if err := e.collectRows(ctx, tx, tc.Table, where, 0, out); err != nil {
				return err
			}
			if !enqueued[tc.Table] {
				enqueued[tc.Table] = true
				*queue = append(*queue, tc.Table)
			}
		}
	}
	return nil
}

// -------------------------------------------------------------------------
// Core fetch helpers
// -------------------------------------------------------------------------

func (e *Exporter) markVisited(table string, pk string) bool {
	if _, ok := e.visited[table]; !ok {
		e.visited[table] = make(map[string]bool)
	}
	if e.visited[table][pk] {
		return true
	}
	e.visited[table][pk] = true
	return false
}

func (e *Exporter) visitedPKs(table string) []string {
	pks := make([]string, 0, len(e.visited[table]))
	for pk := range e.visited[table] {
		pks = append(pks, pk)
	}
	return pks
}

// capturePolyData records discriminator+fk value pairs for tables with virtual edges.
func (e *Exporter) capturePolyData(table string, colNames []string, vals []interface{}) {
	virtualEdges, ok := e.g.VirtualEdges[table]
	if !ok || len(virtualEdges) == 0 {
		return
	}
	// Build a column-index lookup once.
	colIdx := make(map[string]int, len(colNames))
	for i, c := range colNames {
		colIdx[c] = i
	}

	for _, ve := range virtualEdges {
		discIdx, hasDisc := colIdx[ve.DiscriminatorCol]
		fkIdx, hasFK := colIdx[ve.ChildColumn]
		if !hasDisc || !hasFK {
			continue
		}
		discVal := fmt.Sprintf("%v", vals[discIdx])
		fkVal := fmt.Sprintf("%v", vals[fkIdx])
		if discVal == "<nil>" || fkVal == "<nil>" {
			continue
		}

		if e.polyData[table] == nil {
			e.polyData[table] = make(map[string][]polyPair)
		}
		e.polyData[table][ve.DiscriminatorCol] = append(
			e.polyData[table][ve.DiscriminatorCol],
			polyPair{discVal: discVal, fkVal: fkVal},
		)
	}
}

func (e *Exporter) fetchAndEmit(ctx context.Context, tx pgx.Tx, w io.Writer, table string, whereClause string, limit int) ([]string, error) {
	cols := e.schema.Columns[table]
	if len(cols) == 0 {
		return nil, nil
	}
	colNames := colNameSlice(cols)
	query := buildQuery(e.cfg.Schema, table, colNames, whereClause, limit)

	rows, err := tx.Query(ctx, query)
	if err != nil {
		return nil, fmt.Errorf("query %s: %w", table, err)
	}
	defer rows.Close()

	pkCols := e.schema.PrimaryKeys[table]
	var pks []string

	for rows.Next() {
		vals, err := rows.Values()
		if err != nil {
			return nil, fmt.Errorf("row values %s: %w", table, err)
		}
		pk := buildPK(pkCols, colNames, vals)
		if e.markVisited(table, pk) {
			continue
		}
		pks = append(pks, pk)
		e.applyMasking(table, cols, vals)
		e.capturePolyData(table, colNames, vals)
		fmt.Fprintf(w, "INSERT INTO %s.%s (%s) VALUES (%s) ON CONFLICT DO NOTHING;\n",
			quoteIdent(e.cfg.Schema), quoteIdent(table),
			strings.Join(quotedColNames(colNames), ", "),
			formatValues(cols, vals),
		)
		e.RowCounts[table]++
	}
	return pks, rows.Err()
}

func (e *Exporter) collectRows(ctx context.Context, tx pgx.Tx, table string, whereClause string, limit int, out *[]Row) error {
	cols := e.schema.Columns[table]
	if len(cols) == 0 {
		return nil
	}
	colNames := colNameSlice(cols)
	query := buildQuery(e.cfg.Schema, table, colNames, whereClause, limit)

	rows, err := tx.Query(ctx, query)
	if err != nil {
		return fmt.Errorf("query %s: %w", table, err)
	}
	defer rows.Close()

	pkCols := e.schema.PrimaryKeys[table]
	for rows.Next() {
		vals, err := rows.Values()
		if err != nil {
			return fmt.Errorf("row values %s: %w", table, err)
		}
		pk := buildPK(pkCols, colNames, vals)
		if e.markVisited(table, pk) {
			continue
		}
		e.applyMasking(table, cols, vals)
		e.capturePolyData(table, colNames, vals)
		*out = append(*out, Row{Table: table, ColNames: colNames, Cols: cols, Vals: vals})
		e.RowCounts[table]++
	}
	return rows.Err()
}

// -------------------------------------------------------------------------
// Masking
// -------------------------------------------------------------------------

// applyMasking applies config rules first, falling back to auto-heuristics.
func (e *Exporter) applyMasking(table string, cols []introspect.Column, vals []interface{}) {
	if e.masker == nil {
		return
	}
	// Build a temporary config view for rule lookups.
	ruleset := config.Config{Rules: e.cfg.Rules}

	for i, col := range cols {
		if vals[i] == nil {
			continue
		}
		strVal := fmt.Sprintf("%v", vals[i])

		if rule := ruleset.FindRule(table, col.Name); rule != nil {
			masked := e.masker.ApplyTransform(string(rule.Transform), col.Name, strVal)
			if masked != strVal {
				vals[i] = masked
			}
		} else {
			masked := e.masker.MaskColumn(col.Name, strVal)
			if masked != strVal {
				vals[i] = masked
			}
		}
	}
}

// -------------------------------------------------------------------------
// Helpers
// -------------------------------------------------------------------------

func buildSeedClauses(where string, limit int) (string, string) {
	w, l := "", ""
	if where != "" {
		w = "WHERE " + where
	}
	if limit > 0 {
		l = fmt.Sprintf("LIMIT %d", limit)
	}
	return w, l
}

func colNameSlice(cols []introspect.Column) []string {
	names := make([]string, len(cols))
	for i, c := range cols {
		names[i] = c.Name
	}
	return names
}

func buildQuery(schema, table string, colNames []string, whereClause string, limit int) string {
	q := fmt.Sprintf(`SELECT %s FROM %s.%s`,
		quoteIdents(colNames),
		quoteIdent(schema),
		quoteIdent(table),
	)
	if whereClause != "" {
		q += " WHERE " + whereClause
	}
	if limit > 0 {
		q += fmt.Sprintf(" LIMIT %d", limit)
	}
	return q
}

func quoteIdent(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

func quoteIdents(ss []string) string {
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = quoteIdent(s)
	}
	return strings.Join(parts, ", ")
}

func quotedColNames(names []string) []string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = quoteIdent(n)
	}
	return out
}

func buildPK(pkCols []string, colNames []string, vals []interface{}) string {
	if len(pkCols) == 0 {
		return fmt.Sprintf("%v", vals)
	}
	parts := make([]string, 0, len(pkCols))
	for _, pk := range pkCols {
		for j, col := range colNames {
			if col == pk {
				parts = append(parts, fmt.Sprintf("%v", vals[j]))
				break
			}
		}
	}
	return strings.Join(parts, ",")
}

func formatValues(cols []introspect.Column, vals []interface{}) string {
	parts := make([]string, len(vals))
	for i, v := range vals {
		parts[i] = formatValue(cols[i], v)
	}
	return strings.Join(parts, ", ")
}

func formatValue(col introspect.Column, v interface{}) string {
	if v == nil {
		return "NULL"
	}
	switch val := v.(type) {
	case bool:
		if val {
			return "TRUE"
		}
		return "FALSE"
	case int, int8, int16, int32, int64,
		uint, uint8, uint16, uint32, uint64,
		float32, float64:
		return fmt.Sprintf("%v", val)
	case []byte:
		dt := strings.ToLower(col.DataType)
		if strings.Contains(dt, "json") {
			return "'" + escapeSQLString(string(val)) + "'"
		}
		return fmt.Sprintf("'\\x%s'", fmt.Sprintf("%x", val))
	case time.Time:
		return fmt.Sprintf("'%s'", val.UTC().Format(time.RFC3339Nano))
	case [16]byte:
		return fmt.Sprintf("'%s'", formatUUID(val))
	default:
		return "'" + escapeSQLString(fmt.Sprintf("%v", val)) + "'"
	}
}

func escapeSQLString(s string) string {
	return strings.ReplaceAll(s, "'", "''")
}

func formatUUID(b [16]byte) string {
	return fmt.Sprintf("%08x-%04x-%04x-%04x-%012x",
		b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}

func formatStringList(ss []string) string {
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = "'" + escapeSQLString(s) + "'"
	}
	return strings.Join(parts, ", ")
}
