// Config holds export configuration.
type Config struct {
	Schema          string
	AnonymizePII    bool
	Salt            string
	MaxRowsPerTable int // 0 = unlimited
	MaxDepth        int // 0 = unlimited (downward traversal only)
	Rules           []config.Rule // declarative masking rules from dbdrain.yaml
}

// polyPair holds a (discriminatorValue, fkValue) pair captured during row emission.
type polyPair struct {
	discVal string // e.g. "post"
	fkVal   string // e.g. "123"
}

// Exporter orchestrates database slicing, dependency closure, and data transfer.
type Exporter struct {
	conn    *pgx.Conn
	schema  *introspect.Schema
	g       *graph.Graph
	sccs    []graph.SCC
	cfg     Config
	masker  *anonymize.Masker
	visited map[string]map[string]bool // table -> set of row PKs

	// polyData: child_table -> discriminatorCol -> []polyPair
	// Populated during row iteration for tables that have virtual FK edges.
	polyData map[string]map[string][]polyPair

	// RowCounts tracks rows emitted/streamed per table (for summary + verify).
	RowCounts map[string]int
}

// New creates a new Exporter.
func New(conn *pgx.Conn, schema *introspect.Schema, g *graph.Graph, sccs []graph.SCC, cfg Config) *Exporter {
	var masker *anonymize.Masker
	if cfg.AnonymizePII {
		masker = anonymize.New(cfg.Salt)
	}
	return &Exporter{
		conn:      conn,
		schema:    schema,
		g:         g,
		sccs:      sccs,
		cfg:       cfg,
		masker:    masker,
		visited:   make(map[string]map[string]bool),
		polyData:  make(map[string]map[string][]polyPair),
		RowCounts: make(map[string]int),
	}
}

// hasCycles returns true if any SCC has a cycle.
func (e *Exporter) hasCycles() bool {
	for _, scc := range e.sccs {
		if scc.HasCycle {
			return true
		}
	}
	return false
}

// -------------------------------------------------------------------------
// SQL emission mode (Writing SQL to file or stdout)
// -------------------------------------------------------------------------

// Export writes the full SQL dump to w, starting from the anchor table/query.
func (e *Exporter) Export(ctx context.Context, w io.Writer, anchorTable string, anchorWhere string, anchorLimit int) error {
	fmt.Fprintf(w, "-- Generated by dbdrain v0.4.0 on %s\n", time.Now().UTC().Format(time.RFC3339))
	fmt.Fprintf(w, "-- Anchor: %s WHERE %s LIMIT %d\n\n", anchorTable, anchorWhere, anchorLimit)
	fmt.Fprintln(w, "BEGIN;")
	if e.hasCycles() {
		fmt.Fprintln(w, "SET CONSTRAINTS ALL DEFERRED;")
	}
	fmt.Fprintln(w, "")

	tx, err := e.conn.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.RepeatableRead, AccessMode: pgx.ReadOnly})
	if err != nil {
		return fmt.Errorf("begin tx: %w", err)
	}
	defer tx.Rollback(ctx)

	if err := e.resolveSelfRef(ctx, tx, w, anchorTable, anchorWhere, anchorLimit); err != nil {
		return fmt.Errorf("resolve self-ref: %w", err)
	}
	if _, err := e.fetchAndEmit(ctx, tx, w, anchorTable, anchorWhere, anchorLimit); err != nil {
		return fmt.Errorf("fetch anchor: %w", err)
	}
	if err := e.bfsParents(ctx, tx, w, anchorTable); err != nil {
		return fmt.Errorf("traverse parents: %w", err)
	}
	if err := e.bfsChildren(ctx, tx, w, anchorTable, 0); err != nil {
		return fmt.Errorf("traverse children: %w", err)
	}

	fmt.Fprintln(w, "")
	fmt.Fprintln(w, "COMMIT;")
	return nil
}

// -------------------------------------------------------------------------
// Direct target streaming mode (Zero-Copy pgx.CopyFromSource with O(1) RAM)
// -------------------------------------------------------------------------

// ExportToTarget executes zero-copy streaming hydration directly against targetConn.
// It streams rows from sourceTx to targetTx table-by-table via pgx.CopyFromSource,
// recycling row value buffers using sync.Pool to guarantee flat O(1) memory usage.
func (e *Exporter) ExportToTarget(
	ctx context.Context,
	targetConn *pgx.Conn,
	anchorTable string,
	anchorWhere string,
	anchorLimit int,
	progressFn func(table string, n int),
) error {
	// 1. Begin snapshot on source database
	sourceTx, err := e.conn.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.RepeatableRead, AccessMode: pgx.ReadOnly})
	if err != nil {
		return fmt.Errorf("begin source tx: %w", err)
	}
	defer sourceTx.Rollback(ctx)

	// 2. Begin transaction on target database
	targetTx, err := targetConn.Begin(ctx)
	if err != nil {
		return fmt.Errorf("begin target tx: %w", err)
	}
	defer targetTx.Rollback(ctx)

	if _, err := targetTx.Exec(ctx, "SET CONSTRAINTS ALL DEFERRED;"); err != nil {
		return fmt.Errorf("set deferred on target: %w", err)
	}

	// 3. Stream self-referencing hierarchy if present
	if err := e.streamSelfRefToTarget(ctx, sourceTx, targetTx, anchorTable, anchorWhere, anchorLimit, progressFn); err != nil {
		return fmt.Errorf("stream self-ref to target: %w", err)
	}

	// 4. Stream anchor seed rows directly to target
	if err := e.streamAnchorToTarget(ctx, sourceTx, targetTx, anchorTable, anchorWhere, anchorLimit, progressFn); err != nil {
		return fmt.Errorf("stream anchor to target: %w", err)
	}

	// 5. Upward BFS traversal: stream mandatory parent tables
	if err := e.bfsParentsToTarget(ctx, sourceTx, targetTx, anchorTable, progressFn); err != nil {
		return fmt.Errorf("stream parents to target: %w", err)
	}

	// 6. Downward BFS traversal: stream child tables (bounded by --depth & --max-rows-per-table)
	if err := e.bfsChildrenToTarget(ctx, sourceTx, targetTx, anchorTable, progressFn); err != nil {
		return fmt.Errorf("stream children to target: %w", err)
	}

	return targetTx.Commit(ctx)
}

// streamToTarget executes a source query, wraps the live cursor in a CursorCopySource,
// and streams it directly to targetTx.CopyFrom with zero intermediate row allocations.
func (e *Exporter) streamToTarget(
	ctx context.Context,
	rows pgx.Rows,
	targetTx pgx.Tx,
	table string,
	progressFn func(table string, n int),
) error {
	if rows == nil {
		return nil
	}
	defer rows.Close()

	cols := e.schema.Columns[table]
	if len(cols) == 0 {
		return nil
	}
	colNames := colNameSlice(cols)
	pkCols := e.schema.PrimaryKeys[table]

	src := NewCursorCopySource(rows, table, cols, colNames, pkCols, e, progressFn)
	defer src.Close()

	_, err := targetTx.CopyFrom(
		ctx,
		pgx.Identifier{e.cfg.Schema, table},
		colNames,
		src,
	)
	if err != nil {
		return fmt.Errorf("copy into %s: %w", table, err)
	}
	return nil
}

func (e *Exporter) streamAnchorToTarget(
	ctx context.Context,
	sourceTx pgx.Tx,
	targetTx pgx.Tx,
	table string,
	where string,
	limit int,
	progressFn func(table string, n int),
) error {
	cols := e.schema.Columns[table]
	if len(cols) == 0 {
		return nil
	}
	colNames := colNameSlice(cols)
	query := buildQuery(e.cfg.Schema, table, colNames, where, limit)

	rows, err := sourceTx.Query(ctx, query)
	if err != nil {
		return fmt.Errorf("query anchor %s: %w", table, err)
	}

	return e.streamToTarget(ctx, rows, targetTx, table, progressFn)
}

func (e *Exporter) streamSelfRefToTarget(
	ctx context.Context,
	sourceTx pgx.Tx,
	targetTx pgx.Tx,
	table string,
	anchorWhere string,
	limit int,
	progressFn func(table string, n int),
) error {
	edge := e.selfRefEdge(table)
	if edge == nil || len(edge.FromColumns) != 1 || len(edge.ToColumns) != 1 {
		return nil
	}
	childCol, parentCol := edge.FromColumns[0], edge.ToColumns[0]
	cols := e.schema.Columns[table]
	if len(cols) == 0 {
		return nil
	}
	colNames := colNameSlice(cols)
	selectCols := "t." + strings.Join(colNames, ", t.")
	seedWhere, seedLimit := buildSeedClauses(anchorWhere, limit)

	cteSQL := fmt.Sprintf(`
WITH RECURSIVE hierarchy AS (
  SELECT %s FROM %s.%s t %s %s
  UNION
  SELECT %s FROM %s.%s t INNER JOIN hierarchy h ON t.%s = h.%s
  UNION
  SELECT %s FROM %s.%s t INNER JOIN hierarchy h ON t.%s = h.%s
)
SELECT DISTINCT * FROM hierarchy`,
		selectCols, quoteIdent(e.cfg.Schema), quoteIdent(table), seedWhere, seedLimit,
		selectCols, quoteIdent(e.cfg.Schema), quoteIdent(table), quoteIdent(parentCol), quoteIdent(childCol),
		selectCols, quoteIdent(e.cfg.Schema), quoteIdent(table), quoteIdent(childCol), quoteIdent(parentCol),
	)

	rows, err := sourceTx.Query(ctx, cteSQL)
	if err != nil {
		return fmt.Errorf("recursive CTE for %s: %w", table, err)
	}

	return e.streamToTarget(ctx, rows, targetTx, table, progressFn)
}

func (e *Exporter) bfsParentsToTarget(
	ctx context.Context,
	sourceTx pgx.Tx,
	targetTx pgx.Tx,
	startTable string,
	progressFn func(table string, n int),
) error {
	queue := []string{startTable}
	enqueued := map[string]bool{startTable: true}

	for len(queue) > 0 {
		table := queue[0]
		queue = queue[1:]

		for _, edge := range e.g.OutEdges[table] {
			parent := edge.ToTable
			if parent == table || len(edge.ToColumns) != 1 {
				continue
			}
			fkVals := e.visitedPKs(table)
			if len(fkVals) == 0 {
				continue
			}

			parentCols := e.schema.Columns[parent]
			colNames := colNameSlice(parentCols)
			colInfo := findColumnByName(parentCols, edge.ToColumns[0])

			rows, err := queryByIDs(ctx, sourceTx, e.cfg.Schema, parent, colNames, edge.ToColumns[0], colInfo, fkVals, 0)
			if err != nil {
				return fmt.Errorf("query parents of %s: %w", parent, err)
			}

			if err := e.streamToTarget(ctx, rows, targetTx, parent, progressFn); err != nil {
				return err
			}

			if !enqueued[parent] {
				enqueued[parent] = true
				queue = append(queue, parent)
			}
		}

		// Virtual FK (polymorphic) parents
		for _, ve := range e.g.VirtualEdges[table] {
			grouped := map[string][]string{}
			for _, pp := range e.polyData[table][ve.DiscriminatorCol] {
				grouped[pp.discVal] = append(grouped[pp.discVal], pp.fkVal)
			}
			for discVal, fkVals := range grouped {
				tc, ok := ve.Mappings[discVal]
				if !ok {
					continue
				}
				parentCols := e.schema.Columns[tc.Table]
				colNames := colNameSlice(parentCols)
				colInfo := findColumnByName(parentCols, tc.Column)

				rows, err := queryByIDs(ctx, sourceTx, e.cfg.Schema, tc.Table, colNames, tc.Column, colInfo, fkVals, 0)
				if err != nil {
					return fmt.Errorf("virtual FK query (%s→%s): %w", table, tc.Table, err)
				}

				if err := e.streamToTarget(ctx, rows, targetTx, tc.Table, progressFn); err != nil {
					return err
				}

				if !enqueued[tc.Table] {
					enqueued[tc.Table] = true
					queue = append(queue, tc.Table)
				}
			}
		}
	}
	return nil
}

func (e *Exporter) bfsChildrenToTarget(
	ctx context.Context,
	sourceTx pgx.Tx,
	targetTx pgx.Tx,
	startTable string,
	progressFn func(table string, n int),
) error {
	type work struct {
		table string
		depth int
	}
	queue := []work{{startTable, 0}}
	enqueued := map[string]bool{startTable: true}

	for len(queue) > 0 {
		item := queue[0]
		queue = queue[1:]

		if e.cfg.MaxDepth > 0 && item.depth >= e.cfg.MaxDepth {
			continue
		}

		for _, edge := range e.g.InEdges[item.table] {
			child := edge.FromTable
			if child == item.table || len(edge.FromColumns) != 1 {
				continue
			}
			fkVals := e.visitedPKs(item.table)
			if len(fkVals) == 0 {
				continue
			}

			childCols := e.schema.Columns[child]
			colNames := colNameSlice(childCols)
			colInfo := findColumnByName(childCols, edge.FromColumns[0])

			rows, err := queryByIDs(ctx, sourceTx, e.cfg.Schema, child, colNames, edge.FromColumns[0], colInfo, fkVals, e.cfg.MaxRowsPerTable)
			if err != nil {
				return fmt.Errorf("query children %s: %w", child, err)
			}

			if err := e.streamToTarget(ctx, rows, targetTx, child, progressFn); err != nil {
				return err
			}

			if !enqueued[child] {
				enqueued[child] = true
				queue = append(queue, work{child, item.depth + 1})
			}
		}
	}
	return nil
}

// -------------------------------------------------------------------------
// Self-referencing hierarchy resolution (SQL text emission path)
// -------------------------------------------------------------------------

func (e *Exporter) isSelfRef(table string) bool {
	for _, edge := range e.g.OutEdges[table] {
		if edge.ToTable == table {
			return true
		}
	}
	return false
}

func (e *Exporter) selfRefEdge(table string) *graph.Edge {
	for i, edge := range e.g.OutEdges[table] {
		if edge.ToTable == table {
			return &e.g.OutEdges[table][i]
		}
	}
	return nil
}

func (e *Exporter) resolveSelfRef(ctx context.Context, tx pgx.Tx, w io.Writer, table string, anchorWhere string, limit int) error {
	edge := e.selfRefEdge(table)
	if edge == nil || len(edge.FromColumns) != 1 || len(edge.ToColumns) != 1 {
		return nil
	}
	childCol, parentCol := edge.FromColumns[0], edge.ToColumns[0]
	cols := e.schema.Columns[table]
	if len(cols) == 0 {
		return nil
	}
	colNames := colNameSlice(cols)
	selectCols := "t." + strings.Join(colNames, ", t.")
	seedWhere, seedLimit := buildSeedClauses(anchorWhere, limit)

	cteSQL := fmt.Sprintf(`
WITH RECURSIVE hierarchy AS (
  SELECT %s FROM %s.%s t %s %s
  UNION
  SELECT %s FROM %s.%s t INNER JOIN hierarchy h ON t.%s = h.%s
  UNION
  SELECT %s FROM %s.%s t INNER JOIN hierarchy h ON t.%s = h.%s
)
SELECT DISTINCT * FROM hierarchy`,
		selectCols, quoteIdent(e.cfg.Schema), quoteIdent(table), seedWhere, seedLimit,
		selectCols, quoteIdent(e.cfg.Schema), quoteIdent(table), quoteIdent(parentCol), quoteIdent(childCol),
		selectCols, quoteIdent(e.cfg.Schema), quoteIdent(table), quoteIdent(childCol), quoteIdent(parentCol),
	)

	rows, err := tx.Query(ctx, cteSQL)
	if err != nil {
		return fmt.Errorf("recursive CTE for %s: %w", table, err)
	}
	defer rows.Close()

	pkCols := e.schema.PrimaryKeys[table]
	for rows.Next() {
		vals, err := rows.Values()
		if err != nil {
			return err
		}
		pk := buildPK(pkCols, colNames, vals)
		if e.markVisited(table, pk) {
			continue
		}
		e.applyMasking(table, cols, vals)
		e.capturePolyData(table, colNames, vals)
		fmt.Fprintf(w, "INSERT INTO %s.%s (%s) VALUES (%s) ON CONFLICT DO NOTHING;\n",
			quoteIdent(e.cfg.Schema), quoteIdent(table),
			strings.Join(quotedColNames(colNames), ", "),
			formatValues(cols, vals),
		)
		e.RowCounts[table]++
	}
	return rows.Err()
}

// -------------------------------------------------------------------------
// BFS traversal — SQL emission path
// -------------------------------------------------------------------------

func (e *Exporter) bfsParents(ctx context.Context, tx pgx.Tx, w io.Writer, startTable string) error {
	queue := []string{startTable}
	enqueued := map[string]bool{startTable: true}

	for len(queue) > 0 {
		table := queue[0]
		queue = queue[1:]

		for _, edge := range e.g.OutEdges[table] {
			parent := edge.ToTable
			if parent == table || len(edge.ToColumns) != 1 {
				continue
			}
			fkVals := e.visitedPKs(table)
			if len(fkVals) == 0 {
				continue
			}

			parentCols := e.schema.Columns[parent]
			colNames := colNameSlice(parentCols)
			colInfo := findColumnByName(parentCols, edge.ToColumns[0])

			rows, err := queryByIDs(ctx, tx, e.cfg.Schema, parent, colNames, edge.ToColumns[0], colInfo, fkVals, 0)
			if err != nil {
				return fmt.Errorf("query parents (%s): %w", parent, err)
			}

			if _, err := e.emitFromRows(rows, w, parent); err != nil {
				return err
			}

			if !enqueued[parent] {
				enqueued[parent] = true
				queue = append(queue, parent)
			}
		}

		// Virtual FK (polymorphic) parents
		if err := e.resolveVirtualParents(ctx, tx, w, table, &queue, enqueued); err != nil {
			return err
		}
	}
	return nil
}

