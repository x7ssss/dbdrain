package drain

import (
	"context"
	"fmt"
	"io"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/x7ssss/dbdrain/internal/anonymize"
	"github.com/x7ssss/dbdrain/internal/graph"
	"github.com/x7ssss/dbdrain/internal/introspect"
)

// Config holds export configuration.
type Config struct {
	Schema       string
	AnonymizePII bool
	Salt         string
}

// Exporter streams SQL INSERT statements to a writer.
type Exporter struct {
	conn    *pgx.Conn
	schema  *introspect.Schema
	g       *graph.Graph
	sccs    []graph.SCC
	cfg     Config
	masker  *anonymize.Masker
	visited map[string]map[string]bool // table -> set of row PKs
}

// New creates a new Exporter.
func New(conn *pgx.Conn, schema *introspect.Schema, g *graph.Graph, sccs []graph.SCC, cfg Config) *Exporter {
	var masker *anonymize.Masker
	if cfg.AnonymizePII {
		masker = anonymize.New(cfg.Salt)
	}
	return &Exporter{
		conn:    conn,
		schema:  schema,
		g:       g,
		sccs:    sccs,
		cfg:     cfg,
		masker:  masker,
		visited: make(map[string]map[string]bool),
	}
}

// hasCycles returns true if any SCC has a cycle.
func (e *Exporter) hasCycles() bool {
	for _, scc := range e.sccs {
		if scc.HasCycle {
			return true
		}
	}
	return false
}

// Export writes the full SQL dump to w, starting from the anchor table/query.
func (e *Exporter) Export(ctx context.Context, w io.Writer, anchorTable string, anchorWhere string, anchorLimit int) error {
	// Write SQL header
	fmt.Fprintf(w, "-- Generated by dbdrain on %s\n", time.Now().UTC().Format(time.RFC3339))
	fmt.Fprintf(w, "-- Anchor: %s WHERE %s LIMIT %d\n\n", anchorTable, anchorWhere, anchorLimit)
	fmt.Fprintln(w, "BEGIN;")
	if e.hasCycles() {
		fmt.Fprintln(w, "SET CONSTRAINTS ALL DEFERRED;")
	}
	fmt.Fprintln(w, "")

	// Run inside a REPEATABLE READ snapshot transaction for consistency
	tx, err := e.conn.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.RepeatableRead, AccessMode: pgx.ReadOnly})
	if err != nil {
		return fmt.Errorf("begin tx: %w", err)
	}
	defer tx.Rollback(ctx)

	// Fetch anchor rows
	anchorPKs, err := e.fetchAndEmit(ctx, tx, w, anchorTable, anchorWhere, anchorLimit)
	if err != nil {
		return fmt.Errorf("fetch anchor: %w", err)
	}
	_ = anchorPKs

	// Upward traversal: fetch parent rows required by FK constraints
	if err := e.traverseParents(ctx, tx, w, anchorTable); err != nil {
		return fmt.Errorf("traverse parents: %w", err)
	}

	// Downward traversal: fetch direct child rows
	if err := e.traverseChildren(ctx, tx, w, anchorTable); err != nil {
		return fmt.Errorf("traverse children: %w", err)
	}

	fmt.Fprintln(w, "")
	fmt.Fprintln(w, "COMMIT;")
	return nil
}

// markVisited marks a row as visited. Returns true if already visited.
func (e *Exporter) markVisited(table string, pk string) bool {
	if _, ok := e.visited[table]; !ok {
		e.visited[table] = make(map[string]bool)
	}
	if e.visited[table][pk] {
		return true
	}
	e.visited[table][pk] = true
	return false
}

// fetchAndEmit fetches rows from a table and emits INSERT statements.
func (e *Exporter) fetchAndEmit(ctx context.Context, tx pgx.Tx, w io.Writer, table string, whereClause string, limit int) ([]string, error) {
	cols := e.schema.Columns[table]
	if len(cols) == 0 {
		return nil, nil
	}

	colNames := make([]string, len(cols))
	for i, c := range cols {
		colNames[i] = c.Name
	}

	query := fmt.Sprintf(`SELECT %s FROM %s.%s`,
		quoteIdents(colNames),
		quoteIdent(e.cfg.Schema),
		quoteIdent(table),
	)
	if whereClause != "" {
		query += " WHERE " + whereClause
	}
	if limit > 0 {
		query += fmt.Sprintf(" LIMIT %d", limit)
	}

	rows, err := tx.Query(ctx, query)
	if err != nil {
		return nil, fmt.Errorf("query %s: %w", table, err)
	}
	defer rows.Close()

	pkCols := e.schema.PrimaryKeys[table]
	var pks []string

	for rows.Next() {
		vals, err := rows.Values()
		if err != nil {
			return nil, fmt.Errorf("row values %s: %w", table, err)
		}

		// Build PK string for dedup
		pk := buildPK(pkCols, colNames, vals)
		if e.markVisited(table, pk) {
			continue
		}
		pks = append(pks, pk)

		// Apply PII masking
		if e.masker != nil {
			for i, col := range cols {
				if vals[i] != nil {
					strVal := fmt.Sprintf("%v", vals[i])
					masked := e.masker.MaskColumn(col.Name, strVal)
					if masked != strVal {
						vals[i] = masked
					}
				}
			}
		}

		// Emit INSERT
		fmt.Fprintf(w, "INSERT INTO %s.%s (%s) VALUES (%s) ON CONFLICT DO NOTHING;\n",
			quoteIdent(e.cfg.Schema),
			quoteIdent(table),
			strings.Join(quotedColNames(colNames), ", "),
			formatValues(cols, vals),
		)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("rows err %s: %w", table, err)
	}

	return pks, nil
}

// traverseParents follows FK edges upward to pull in required parent rows.
func (e *Exporter) traverseParents(ctx context.Context, tx pgx.Tx, w io.Writer, table string) error {
	for _, edge := range e.g.OutEdges[table] {
		parent := edge.ToTable
		if parent == table {
			continue // skip self-referential
		}
		// Build WHERE clause based on FK values we already have
		var pksForParent []string
		for pk := range e.visited[table] {
			pksForParent = append(pksForParent, pk)
		}
		if len(edge.ToColumns) == 1 && len(pksForParent) > 0 {
			whereClause := fmt.Sprintf("%s IN (%s)",
				quoteIdent(edge.ToColumns[0]),
				formatStringList(pksForParent),
			)
			if _, err := e.fetchAndEmit(ctx, tx, w, parent, whereClause, 0); err != nil {
				return err
			}
		}
	}
	return nil
}

// traverseChildren follows FK edges downward to pull direct child rows.
func (e *Exporter) traverseChildren(ctx context.Context, tx pgx.Tx, w io.Writer, table string) error {
	for _, edge := range e.g.InEdges[table] {
		child := edge.FromTable
		if child == table {
			continue // skip self-referential
		}
		var pksForChild []string
		for pk := range e.visited[table] {
			pksForChild = append(pksForChild, pk)
		}
		if len(edge.FromColumns) == 1 && len(pksForChild) > 0 {
			whereClause := fmt.Sprintf("%s IN (%s)",
				quoteIdent(edge.FromColumns[0]),
				formatStringList(pksForChild),
			)
			if _, err := e.fetchAndEmit(ctx, tx, w, child, whereClause, 0); err != nil {
				return err
			}
		}
	}
	return nil
}

// --- Helper functions ---

func quoteIdent(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

func quoteIdents(ss []string) string {
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = quoteIdent(s)
	}
	return strings.Join(parts, ", ")
}

func quotedColNames(names []string) []string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = quoteIdent(n)
	}
	return out
}

func buildPK(pkCols []string, colNames []string, vals []interface{}) string {
	if len(pkCols) == 0 {
		// Use all values as key if no PK defined
		return fmt.Sprintf("%v", vals)
	}
	parts := make([]string, 0, len(pkCols))
	for _, pk := range pkCols {
		for j, col := range colNames {
			if col == pk {
				parts = append(parts, fmt.Sprintf("%v", vals[j]))
				break
			}
		}
	}
	return strings.Join(parts, ",")
}

func formatValues(cols []introspect.Column, vals []interface{}) string {
	parts := make([]string, len(vals))
	for i, v := range vals {
		parts[i] = formatValue(cols[i], v)
	}
	return strings.Join(parts, ", ")
}

func formatValue(col introspect.Column, v interface{}) string {
	if v == nil {
		return "NULL"
	}
	switch val := v.(type) {
	case bool:
		if val {
			return "TRUE"
		}
		return "FALSE"
	case int, int8, int16, int32, int64,
		uint, uint8, uint16, uint32, uint64,
		float32, float64:
		return fmt.Sprintf("%v", val)
	case []byte:
		// Could be bytea or JSON
		dt := strings.ToLower(col.DataType)
		if strings.Contains(dt, "json") {
			return "'" + escapeSQLString(string(val)) + "'"
		}
		return fmt.Sprintf("'\\x%s'", fmt.Sprintf("%x", val))
	case time.Time:
		return fmt.Sprintf("'%s'", val.UTC().Format(time.RFC3339Nano))
	case [16]byte:
		// UUID
		return fmt.Sprintf("'%s'", formatUUID(val))
	default:
		return "'" + escapeSQLString(fmt.Sprintf("%v", val)) + "'"
	}
}

func escapeSQLString(s string) string {
	return strings.ReplaceAll(s, "'", "''")
}

func formatUUID(b [16]byte) string {
	return fmt.Sprintf("%08x-%04x-%04x-%04x-%012x",
		b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}

func formatStringList(ss []string) string {
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = "'" + escapeSQLString(s) + "'"
	}
	return strings.Join(parts, ", ")
}
